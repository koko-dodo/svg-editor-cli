import { describe, expect, it } from "vitest";
import { SaxesParser } from "saxes";
import { SvgReader } from "../../src/io/SvgReader";
import { SvgWriter } from "../../src/io/SvgWriter";
import { SvgDocument } from "../../src/model/SvgDocument";
import { Rectangle } from "../../src/model/Rectangle";
import { Circle } from "../../src/model/Circle";
import { Ellipse } from "../../src/model/Ellipse";
import { Line } from "../../src/model/Line";
import { TextShape } from "../../src/model/TextShape";
import { Group } from "../../src/model/Group";

// Hand-authored contract fixture. Never generated by SvgWriter or ShapeSchema.
const external = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 400 300">
  <rect x="-1.5" y="2" width="30" height="40" fill="#abc"/>
  <g id="scene" fill="red" stroke="blue" stroke-width="2.5">
    <circle id="circle1" cx="10" cy="20" r="5"/>
    <g id="nested"><ellipse id="e" cx="2" cy="3" rx="4" ry="5" fill="none"/>
      <line id="l" x1="-2" y1="1" x2="9" y2="8" stroke="black"/>
      <text id="t" x="6" y="7">  A &amp; B &lt;中文&gt; "Q"<![CDATA[<raw>]]>  </text>
      <text id="empty" x="0" y="0"/></g>
  </g><rect id="rect1" x="1" y="2" width="3" height="4"/>
</svg>`;

interface XmlNode { tag: string; attributes: Record<string, string>; text: string; children: XmlNode[] }
// Independent XML parser, with no Reader/model/schema interpretation.
function parseXml(xml: string): XmlNode {
  const stack: XmlNode[] = []; let root: XmlNode | undefined;
  const parser = new SaxesParser({ xmlns: true });
  parser.on("error", error => { throw error; });
  parser.on("opentag", tag => {
    expect(tag.uri).toBe("http://www.w3.org/2000/svg");
    const attributes: Record<string, string> = {};
    for (const attr of Object.values(tag.attributes)) {
      if (attr.uri !== "http://www.w3.org/2000/xmlns/") attributes[attr.name] = attr.value;
    }
    const node: XmlNode = { tag: tag.local, attributes, text: "", children: [] };
    if (stack.length) stack.at(-1)!.children.push(node); else root = node;
    stack.push(node);
  });
  parser.on("text", text => { if (stack.length) stack.at(-1)!.text += text; });
  parser.on("closetag", () => { stack.pop(); });
  parser.write(xml).close();
  return root!;
}

describe("independent SVG contracts (§2, §4.1 and SVG hierarchy)", () => {
  it("imports explicit values, concrete types, text, hierarchy and drawing order", () => {
    const result = new SvgReader().read(external); const doc = result.document;
    expect([doc.width, doc.height, result.elements]).toEqual([400, 300, 9]);
    expect(result.warnings).toEqual([{ code: "assigned-id", tag: "rect", id: "rect2" }]);
    expect(doc.getRootSnapshots().map(s => s.id)).toEqual(["rect2", "scene", "rect1"]);
    expect((doc.getShapeSnapshot("scene") as Group).children.map(s => s.id)).toEqual(["circle1", "nested"]);
    expect((doc.getShapeSnapshot("nested") as Group).children.map(s => s.id)).toEqual(["e", "l", "t", "empty"]);
    const expected = [
      ["rect2", Rectangle, { x: -1.5, y: 2, width: 30, height: 40, fill: "#abc" }, null],
      ["scene", Group, { fill: "red", stroke: "blue", strokeWidth: 2.5 }, null],
      ["circle1", Circle, { cx: 10, cy: 20, r: 5, fill: undefined, stroke: undefined }, "scene"],
      ["nested", Group, { fill: undefined }, "scene"],
      ["e", Ellipse, { cx: 2, cy: 3, rx: 4, ry: 5, fill: "none" }, "nested"],
      ["l", Line, { x1: -2, y1: 1, x2: 9, y2: 8, stroke: "black" }, "nested"],
      ["t", TextShape, { x: 6, y: 7, text: '  A & B <中文> "Q"<raw>  ' }, "nested"],
      ["empty", TextShape, { x: 0, y: 0, text: "" }, "nested"],
      ["rect1", Rectangle, { x: 1, y: 2, width: 3, height: 4, fill: undefined }, null],
    ] as const;
    for (const [id, type, attributes, parent] of expected) {
      const shape = doc.getShapeSnapshot(id);
      expect(shape).toBeInstanceOf(type); expect(shape.id).toBe(id);
      expect(shape).toMatchObject(attributes); expect(doc.getParentId(id)).toBe(parent);
    }
  });

  it("exports literal XML dimensions, namespace, tags, attributes, hierarchy and order", () => {
    const doc = new SvgDocument(320, 240);
    const scene = new Group("scene", { fill: "red", "stroke-width": 2 });
    scene.addChild(new Rectangle("r", -1, 2, 3, 4, { fill: "none" }));
    const nested = new Group("nested");
    nested.addChild(new Circle("c", 5, 6, 7));
    nested.addChild(new Ellipse("e", 8, 9, 10, 11));
    nested.addChild(new Line("l", 12, 13, 14, 15, { stroke: "blue" }));
    nested.addChild(new TextShape("t", 16, 17, ' A & <中文> "Q"\r\n '));
    nested.addChild(new TextShape("empty", 0, 0, ""));
    scene.addChild(nested); doc.addShape(scene); doc.addShape(new Group("last"));
    const result = new SvgWriter().write(doc);
    expect(result.elements).toBe(9);
    expect(result.xml).toContain('xmlns="http://www.w3.org/2000/svg"');
    const leaf = (tag: string, attributes: Record<string, string>, text = ""): XmlNode => ({ tag, attributes, text, children: [] });
    expect(parseXml(result.xml)).toEqual({
      tag: "svg", attributes: { width: "320", height: "240", viewBox: "0 0 320 240" }, text: "", children: [
        { tag: "g", attributes: { id: "scene", fill: "red", "stroke-width": "2" }, text: "", children: [
          leaf("rect", { id: "r", x: "-1", y: "2", width: "3", height: "4", fill: "none" }),
          { tag: "g", attributes: { id: "nested" }, text: "", children: [
            leaf("circle", { id: "c", cx: "5", cy: "6", r: "7" }),
            leaf("ellipse", { id: "e", cx: "8", cy: "9", rx: "10", ry: "11" }),
            leaf("line", { id: "l", x1: "12", y1: "13", x2: "14", y2: "15", stroke: "blue" }),
            leaf("text", { id: "t", x: "16", y: "17" }, ' A & <中文> "Q"\r\n '),
            leaf("text", { id: "empty", x: "0", y: "0" }),
          ] },
        ] }, leaf("g", { id: "last" }),
      ],
    });
  });
});
